"""
SmartRetail AI - Synthetic Retail Demo Simulator
=================================================
IMPORTANT DISCLAIMER & HONEST SYSTEM ARCHITECTURE NOTE:
This module contains an OpenCV color/coordinate heuristic simulator calibrated
exclusively for the synthetic retail simulation video ('videos/store.mp4').
Because the bundled store video renders supermarket shelves and shoppers as
color-coded geometric blocks, this heuristic matches those colors and coordinates.

It is NOT a trained neural network and will not recognize products in real CCTV
or smartphone footage. All detections generated by this module are explicitly
tagged with `source="demo_simulation"` and surfaced to the UI as 'DEMO SIMULATION'.

When a real custom SKU model is trained and saved to 'models/trained/best.pt',
the system automatically switches to `source="trained_sku_model"` ('TRAINED MODEL').
"""

